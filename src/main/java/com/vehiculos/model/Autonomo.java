package com.vehiculos.model;

/**
 * Interface que define el comportamiento de un vehículo autónomo.
 */
public interface Autonomo {


    /**
     * Activa el piloto automático del vehículo.
     */
    void activarPilotoAutomatico();

    /**
     * Desactiva el piloto automático del vehículo.
     */
    void desactivarPilotoAutomatico();

}
